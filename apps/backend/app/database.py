def using_postgres() -> bool:
    return bool(DATABASE_URL)


def find_seed_file(name: str) -> Path:
    primary = Path("/data") / name
    if primary.exists():
        return primary
    current = Path(__file__).resolve()
    for parent in current.parents:
        candidate = parent / "data" / name
        if candidate.exists():
            return candidate
    return primary


class CursorAdapter:
    def __init__(self, cursor: Any, lastrowid: int | None = None):
        self.cursor = cursor
        self.lastrowid = lastrowid if lastrowid is not None else getattr(cursor, "lastrowid", None)
        self.rowcount = getattr(cursor, "rowcount", -1)

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()


class DatabaseAdapter:
    def __init__(self):
        self.is_postgres = using_postgres()
        if self.is_postgres:
            if psycopg is None:
                raise RuntimeError("DATABASE_URL requiere psycopg instalado.")
            self.connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
        else:
            DB_PATH.parent.mkdir(parents=True, exist_ok=True)
            self.connection = sqlite3.connect(DB_PATH)
            self.connection.row_factory = sqlite3.Row

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        if exc_type:
            self.connection.rollback()
        else:
            self.connection.commit()
        self.connection.close()

    def _query(self, sql: str) -> str:
        if not self.is_postgres:
            return sql
        return sql.replace("?", "%s")

    def execute(self, sql: str, params: tuple[Any, ...] | list[Any] = ()):
        query = self._query(sql)
        returning_id = False
        if self.is_postgres:
            compact = " ".join(query.lower().split())
            returns_id = any(
                compact.startswith(f"insert into {table}")
                for table in (
                    "data_snapshots",
                    "directors",
                    "match_events",
                    "live_predictions",
                    "ingestion_jobs",
                    "match_results_verified",
                    "match_result_confirmations",
                    "model_runs",
                    "match_model_lines",
                    "model_autopsies",
                    "social_publications",
                    "players",
                )
            )
            if returns_id and " returning " not in compact:
                query = f"{query.rstrip()} returning id"
                returning_id = True

        cursor = self.connection.cursor()
        cursor.execute(query, params)
        lastrowid = None
        if returning_id:
            row = cursor.fetchone()
            lastrowid = row["id"] if row else None
        return CursorAdapter(cursor, lastrowid)

    def executemany(self, sql: str, rows: list[tuple[Any, ...]]):
        cursor = self.connection.cursor()
        cursor.executemany(self._query(sql), rows)
        return CursorAdapter(cursor)


def connect() -> DatabaseAdapter:
    return DatabaseAdapter()


def id_column() -> str:
    if using_postgres():
        return "integer primary key generated by default as identity"
    return "integer primary key autoincrement"


def ensure_column(db: DatabaseAdapter, table: str, column: str, definition: str) -> None:
    if db.is_postgres:
        row = db.execute(
            """
            select column_name
            from information_schema.columns
            where table_name = ? and column_name = ?
            """,
            (table, column),
        ).fetchone()
        if not row:
            db.execute(f"alter table {table} add column {column} {definition}")
        return

    columns = db.execute(f"pragma table_info({table})").fetchall()
    if column not in {row["name"] for row in columns}:
        db.execute(f"alter table {table} add column {column} {definition}")


